/**
 * Run the eval harness against the committed judge artifacts and write the honest report.
 *
 *   pnpm judges:eval
 *
 * Produces docs/benchmarks/judge-evals.json (machine-readable baseline for the S5-T4 gate) and
 * docs/benchmarks/judge-evals.md from REAL runs. Deterministic (seeded bootstrap + deterministic
 * scoring), so the committed baseline is stable.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { type JudgeModelArtifact } from "../packages/judge/src/index.js";
import {
  CONCERNS,
  type Concern,
  evaluateConcern,
  logisticScorer,
  constantScorer,
  seededRandomScorer,
  loadOperatingPoints,
  loadConcern,
  renderMarkdown,
  type ConcernReport,
} from "../packages/judge-eval/src/index.js";

const MODELS_DIR = fileURLToPath(new URL("../packages/judge/models", import.meta.url));
const OUT_DIR = fileURLToPath(new URL("../docs/benchmarks", import.meta.url));
const GENERATED_AT = process.env.GENERATED_AT ?? "2026-07-25T00:00:00.000Z";

function loadArtifact(concern: Concern): JudgeModelArtifact {
  return JSON.parse(
    readFileSync(join(MODELS_DIR, `${concern}.model.json`), "utf8"),
  ) as JudgeModelArtifact;
}

async function main(): Promise<void> {
  const op = loadOperatingPoints();
  const reports: ConcernReport[] = [];
  const datasetHashes: Record<string, string> = {};

  for (const concern of CONCERNS) {
    const artifact = loadArtifact(concern);
    const scorer = logisticScorer(artifact);
    const threshold = op.points.thresholds[concern];
    const controls = [
      constantScorer("always-positive (majority-class control)", 1.0),
      seededRandomScorer("seeded-random", 42),
    ];
    const report = await evaluateConcern(concern, scorer, threshold, op.hash, { controls });
    reports.push(report);
    datasetHashes[concern] = loadConcern(concern).manifest.datasetHash;
    console.log(
      `${concern}: PR-AUC ${(report.clean.prAuc * 100).toFixed(1)}% · clean recall ${(report.clean.recall * 100).toFixed(1)}% · ` +
        `worst adversarial recall ${(Math.min(...report.adversarial.map((a) => a.recall)) * 100).toFixed(1)}%`,
    );
  }

  const humanReviewStatus = loadConcern("finra-promissory").manifest.humanReview.status;
  const hardNegativeShare: Record<string, number> = {};
  for (const concern of CONCERNS) {
    const neg = loadConcern(concern).splits.find((s) => s.suite === "clean-negative")!;
    hardNegativeShare[concern] = neg.hardNegatives / neg.count;
  }
  const json = {
    schemaVersion: "1.0.0",
    generatedAt: GENERATED_AT,
    operatingPointsHash: op.hash,
    datasetHashes,
    reports,
  };
  const md = renderMarkdown(reports, {
    generatedNote: `Generated by \`pnpm judges:eval\` from real runs of the committed logistic judges (${GENERATED_AT}).`,
    operatingPointsHash: op.hash,
    datasetHashes,
    hardNegativeShare,
    humanReviewStatus,
    generatorIdentity:
      "template-expansion (Pharos engineering); no external LLM in the committed pipeline",
    nativeLanguageMethod:
      "Spanish/German suites are natively authored (not machine-translated); native-speaker review outstanding.",
    sharedFamilyLimitation:
      "Eval text is engineer-authored templates, not LLM-sampled — it shares no generator family with any later distilled model.",
  });

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "judge-evals.json"), JSON.stringify(json, null, 2) + "\n", "utf8");
  writeFileSync(join(OUT_DIR, "judge-evals.md"), md + "\n", "utf8");
  console.log(`\nWrote docs/benchmarks/judge-evals.{json,md}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
